from __future__ import annotations

import json
import os
import sqlite3

from pathlib import Path

import psycopg

from dotenv import load_dotenv
from psycopg.rows import dict_row


# ============================================================
# CONFIGURATION
# ============================================================

ROOT = Path(__file__).resolve().parent

load_dotenv(ROOT / ".env")

SQLITE_PATH = ROOT / "data" / "bugfix.sqlite3"

DATABASE_URL = os.getenv("DATABASE_URL", "").strip()


# ============================================================
# VALIDATE CONFIGURATION
# ============================================================

if not DATABASE_URL:

    raise RuntimeError(
        "DATABASE_URL is empty. "
        "Set it to your Neon PostgreSQL connection string "
        "in backend/.env before running this script."
    )


if not SQLITE_PATH.is_file():

    raise FileNotFoundError(
        f"SQLite database not found: {SQLITE_PATH}"
    )


# ============================================================
# READ SQLITE DATA
# ============================================================

sqlite_connection = sqlite3.connect(SQLITE_PATH)

sqlite_connection.row_factory = sqlite3.Row

try:

    rows = sqlite_connection.execute(
        """
        SELECT
            id,
            title,
            url,
            technology,
            summary,
            problem,
            diagnosis,
            solution,
            result,
            image_paths,
            published,
            created_at,
            updated_at
        FROM cases
        ORDER BY id
        """
    ).fetchall()

finally:

    sqlite_connection.close()


print(f"Found {len(rows)} case studies in SQLite.")


# ============================================================
# CREATE TARGET TABLE AND COPY DATA
# ============================================================

create_table_sql = """
    CREATE TABLE IF NOT EXISTS cases (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        url TEXT NOT NULL,
        technology TEXT NOT NULL DEFAULT '',
        summary TEXT NOT NULL DEFAULT '',
        problem TEXT NOT NULL,
        diagnosis TEXT NOT NULL DEFAULT '',
        solution TEXT NOT NULL,
        result TEXT NOT NULL DEFAULT '',
        image_paths TEXT NOT NULL DEFAULT '[]',
        published INTEGER NOT NULL DEFAULT 1,
        created_at BIGINT NOT NULL,
        updated_at BIGINT NOT NULL
    )
"""


insert_sql = """
    INSERT INTO cases (
        id,
        title,
        url,
        technology,
        summary,
        problem,
        diagnosis,
        solution,
        result,
        image_paths,
        published,
        created_at,
        updated_at
    )
    VALUES (
        %(id)s,
        %(title)s,
        %(url)s,
        %(technology)s,
        %(summary)s,
        %(problem)s,
        %(diagnosis)s,
        %(solution)s,
        %(result)s,
        %(image_paths)s,
        %(published)s,
        %(created_at)s,
        %(updated_at)s
    )
    ON CONFLICT (id) DO NOTHING
"""


with psycopg.connect(
    DATABASE_URL,
    row_factory=dict_row,
    connect_timeout=15,
) as connection:

    connection.execute(create_table_sql)

    inserted = 0

    for row in rows:

        record = dict(row)

        # Ensure the image metadata is valid JSON.
        raw_images = record.get("image_paths") or "[]"

        try:

            parsed_images = json.loads(raw_images)

            record["image_paths"] = json.dumps(
                parsed_images
            )

        except (ValueError, TypeError):

            record["image_paths"] = "[]"

        cursor = connection.execute(
            insert_sql,
            record,
        )

        inserted += cursor.rowcount

    # Ensure PostgreSQL generates IDs after the imported IDs.
    connection.execute(
        """
        SELECT setval(
            pg_get_serial_sequence('cases', 'id'),
            COALESCE((SELECT MAX(id) FROM cases), 1),
            EXISTS (SELECT 1 FROM cases)
        )
        """
    )


# ============================================================
# VERIFY MIGRATION
# ============================================================

with psycopg.connect(
    DATABASE_URL,
    row_factory=dict_row,
    connect_timeout=15,
) as connection:

    total = connection.execute(
        "SELECT COUNT(*) AS total FROM cases"
    ).fetchone()["total"]


print(f"New rows copied: {inserted}")
print(f"Total rows in Neon: {total}")
print("Migration completed.")