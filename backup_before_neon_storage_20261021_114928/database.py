from __future__ import annotations

import os
import sqlite3

from contextlib import contextmanager
from pathlib import Path
from typing import Any, Iterator

from dotenv import load_dotenv


# ============================================================
# CONFIGURATION
# ============================================================

ROOT = Path(__file__).resolve().parent

# Load environment variables from backend/.env.
load_dotenv(ROOT / ".env")

DATA_DIR = Path(
    os.getenv("DATA_DIR", str(ROOT / "data"))
).resolve()

DB_PATH = DATA_DIR / "bugfix.sqlite3"

# If DATABASE_URL exists, use PostgreSQL.
# Otherwise, use SQLite for local development.
DATABASE_URL = os.getenv("DATABASE_URL", "").strip()

USE_POSTGRES = bool(DATABASE_URL)

DATA_DIR.mkdir(parents=True, exist_ok=True)


# ============================================================
# DATABASE CONNECTION
# ============================================================

@contextmanager
def get_db() -> Iterator[Any]:
    """
    Open a database connection.

    PostgreSQL:
        Uses Neon when DATABASE_URL is configured.

    SQLite:
        Uses backend/data/bugfix.sqlite3 when DATABASE_URL
        is empty.

    Transactions are committed on success and rolled back
    on exceptions.
    """

    if USE_POSTGRES:
        import psycopg

        from psycopg.rows import dict_row

        connection = psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row,
            connect_timeout=15,
        )

        try:
            yield connection
            connection.commit()

        except Exception:
            connection.rollback()
            raise

        finally:
            connection.close()

    else:
        connection = sqlite3.connect(DB_PATH)

        connection.row_factory = sqlite3.Row

        connection.execute("PRAGMA foreign_keys = ON")

        try:
            yield connection
            connection.commit()

        except Exception:
            connection.rollback()
            raise

        finally:
            connection.close()


# ============================================================
# SQL PLACEHOLDERS
# ============================================================

def placeholder() -> str:
    """
    Return the correct parameter placeholder for the database.

    SQLite:     ?
    PostgreSQL: %s
    """

    return "%s" if USE_POSTGRES else "?"


# ============================================================
# DATABASE INITIALIZATION
# ============================================================

def init_db() -> None:
    """
    Create the cases table if it does not already exist.

    The schema is compatible with both SQLite and PostgreSQL.
    """

    if USE_POSTGRES:

        create_table_sql = """
            CREATE TABLE IF NOT EXISTS cases (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title TEXT NOT NULL,
                technology TEXT NOT NULL DEFAULT '',
                summary TEXT NOT NULL DEFAULT '',
                problem TEXT NOT NULL,
                diagnosis TEXT NOT NULL DEFAULT '',
                solution TEXT NOT NULL,
                result TEXT NOT NULL DEFAULT '',
                image_paths TEXT NOT NULL DEFAULT '[]',
                published INTEGER NOT NULL DEFAULT 1,
                created_at BIGINT NOT NULL,
                updated_at BIGINT NOT NULL
            )
        """

    else:

        create_table_sql = """
            CREATE TABLE IF NOT EXISTS cases (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                title TEXT NOT NULL,
                technology TEXT NOT NULL DEFAULT '',
                summary TEXT NOT NULL DEFAULT '',
                problem TEXT NOT NULL,
                diagnosis TEXT NOT NULL DEFAULT '',
                solution TEXT NOT NULL,
                result TEXT NOT NULL DEFAULT '',
                image_paths TEXT NOT NULL DEFAULT '[]',
                published INTEGER NOT NULL DEFAULT 1,
                created_at INTEGER NOT NULL,
                updated_at INTEGER NOT NULL
            )
        """

    with get_db() as connection:
        connection.execute(create_table_sql)


# ============================================================
# CONNECTION STATUS
# ============================================================

def database_status() -> dict[str, str]:
    """
    Test the configured database connection.
    """

    with get_db() as connection:

        if USE_POSTGRES:
            connection.execute("SELECT 1")
            database_type = "postgresql"

        else:
            connection.execute("SELECT 1")
            database_type = "sqlite"

    return {
        "database": database_type,
        "status": "connected",
    }